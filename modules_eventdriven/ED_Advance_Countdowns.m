function SimState = ED_Advance_Countdowns( ...
    SimState, SimParams, skipped_slots)
%ED_ADVANCE_COUNTDOWNS Apply skipped idle-slot AIFS/backoff decrements.

    if skipped_slots <= 0
        return;
    end
    [assigned, ~, active_raw_bss] = ...
        ED_Get_Active_RAW_Assignment(SimState, SimParams);
    assigned = ED_TXOP_Filter_NAV_Contenders( ...
        SimState, SimParams, assigned);

    if ~isempty(assigned)
        lengths = [SimState.Node.TX_Buffer.Length];
        eligible = assigned( ...
            lengths(assigned) > 0 & ...
            ~SimState.ED_TXOP.Active(assigned) & ...
            SimState.n_txnode(assigned) == 0 & ...
            SimState.tx_status(assigned, 1).' == -1 & ...
            SimState.Node.ACK_Timer(assigned, 1).' == -1 & ...
            SimState.ED_RAW_Fit_Blocked_Until(assigned) < SimState.Time);
        aifs = SimState.Node.aifs(eligible);
        backoff_decrements = skipped_slots * ones(size(eligible));
        with_aifs = aifs > 0;
        backoff_decrements(with_aifs) = max(0, ...
            skipped_slots - aifs(with_aifs) + 1);
        SimState.Node.aifs(eligible) = max(0, aifs - skipped_slots);
        SimState.Node.bc(eligible) = ...
            SimState.Node.bc(eligible) - backoff_decrements;
    end

    if isfield(SimState, 'BSS_Interference')
        active = find(active_raw_bss);
        if ~isempty(active)
            SimState.BSS_Interference.RAW_Active_Slots(active) = ...
                SimState.BSS_Interference.RAW_Active_Slots(active) + ...
                skipped_slots;
            SimState.BSS_Interference.RAW_Overlap_Slots(active, active) = ...
                SimState.BSS_Interference.RAW_Overlap_Slots(active, active) + ...
                skipped_slots;
        end

        active_tx = find(SimState.tx_status(:, 1) ~= -1).';
        if ~isempty(active_tx)
            active_bss = unique(SimState.Node.BSS_ID(active_tx));
            SimState.BSS_Interference.TX_Active_Slots(active_bss) = ...
                SimState.BSS_Interference.TX_Active_Slots(active_bss) + ...
                skipped_slots;
            SimState.BSS_Interference.TX_Overlap_Slots( ...
                active_bss, active_bss) = ...
                SimState.BSS_Interference.TX_Overlap_Slots( ...
                active_bss, active_bss) + skipped_slots;
        end
    end
end
