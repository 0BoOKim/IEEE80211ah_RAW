function Profiles = ED_Default_EDCA_Profiles()
%ED_DEFAULT_EDCA_PROFILES Contention parameters used by EDCA experiments.
%
% CWmin and CWmax use the usual zero-based EDCA notation. The simulator
% converts them to window sizes because its backoff draw uses 1..CW.
% A zero TXOP limit retains the IEEE 802.11 single-frame-per-access
% behavior. Camera experiments can replace it with an SDC-scaled limit via
% ED_Configure_SDC_Dependent_TXOP without changing these baseline values.

    Profiles = struct();
    Profiles.AC_BE = struct( ...
        'AIFSN', 3, ...
        'CWmin', 15, ...
        'CWmax', 1023, ...
        'TXOPLimit_us', 0);
    Profiles.AC_VI = struct( ...
        'AIFSN', 2, ...
        'CWmin', 7, ...
        'CWmax', 15, ...
        'TXOPLimit_us', 0);
end
