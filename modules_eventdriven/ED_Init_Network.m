function [SimState, SimParams] = ED_Init_Network(SimParams)
%ED_INIT_NETWORK Reuse topology setup without allocating full-run tx_state.

    if ~isfield(SimParams, 'ED_Channel_History_Slots') || ...
       isempty(SimParams.ED_Channel_History_Slots)
        SimParams.ED_Channel_History_Slots = 4096;
    end

    minimum_history = max([ ...
        SimParams.Net_Congestion_Measure_Interval, ...
        max(SimParams.BSS_T_RAW_Slot_in_Slot), ...
        SimParams.T_ackN]) + 64;
    if SimParams.ED_Channel_History_Slots < minimum_history
        error('ED:ChannelHistoryTooShort', ...
            ['ED_Channel_History_Slots must be at least %d for the current ' ...
             'RAW and congestion-measurement configuration.'], minimum_history);
    end

    full_run_slots = SimParams.N_slot;
    init_params = SimParams;
    init_params.N_slot = min(full_run_slots, ...
        SimParams.ED_Channel_History_Slots);
    SimState = Init_Network(init_params);

    if isfield(SimParams, 'ED_Camera')
        SimState = ED_Apply_Camera_Deployment(SimState, SimParams);
    end

    if isfield(SimState, 'tx_state')
        SimState = rmfield(SimState, 'tx_state');
    end
    SimState.ED_Channel = ED_Channel_Init( ...
        SimParams.N_Node, SimParams.ED_Channel_History_Slots, ...
        SimParams.Net_Congestion_Measure_Interval);
    queue_capacity = Get_Field_Or_Default( ...
        SimParams, 'ED_Initial_Queue_Capacity', 64);
    buffers = cell(1, SimParams.N_Node);
    for node_id = 1:SimParams.N_Node
        buffers{node_id} = ED_Init_TX_Buffer( ...
            SimState.Node.TX_Buffer(node_id), queue_capacity);
    end
    SimState.Node.TX_Buffer = [buffers{:}];
    delay_capacity = Get_Field_Or_Default( ...
        SimParams, 'ED_Initial_Delay_Capacity', 64);
    SimState.Delay = repmat( ...
        ED_Init_Delay_Record(delay_capacity), 1, SimParams.N_Node);

    SimState.ED_Activation_Event_Index = 1;
    SimState.ED_Reference_Active_Count = 0;
    SimState.ED_Next_Physical_Activation_Index = 1;
    SimState.ED_Active_Alarm_IDs = zeros( ...
        1, numel(SimParams.idx_STA_Type1));
    SimState.ED_Active_Alarm_Count = 0;
    SimState.ED_Background_STA_IDs = SimParams.idx_STA_Type0;
    if isfield(SimParams, 'idx_Camera_STA')
        SimState.ED_Background_STA_IDs = setdiff( ...
            SimState.ED_Background_STA_IDs, ...
            SimParams.idx_Camera_STA, 'stable');
    end
    SimState.ED_RAW_Fit_Blocked_Until = zeros(1, SimParams.N_Node);
    % tx_status identifies an ACK destination but not the DATA MPDU GID.
    % Preserve the source GID separately so a delayed ACK cannot complete a
    % newer retransmission of the same queue head.
    SimState.ED_ACK_Source_GID = -ones(1, SimParams.N_Node);
    % Attempted airtime is attributed to the originating STA. ACK airtime
    % is stored against its DATA destination so alarm/camera class shares
    % can be compared without treating the AP as a third traffic class.
    SimState.ED_Airtime = struct( ...
        'DATA_Attempt_Slots', zeros(1, SimParams.N_Node), ...
        'ACK_Attempt_Slots_By_Destination', ...
            zeros(1, SimParams.N_Node));
    SimState = ED_Init_TXOP_State(SimState, SimParams);
    SimState.ED_RAW_Assignment_Cache = cell(1, SimParams.N_AP);
    for bss_id = 1:SimParams.N_AP
        SimState.ED_RAW_Assignment_Cache{bss_id} = cell( ...
            SimParams.BSS_N_RAW(bss_id), 1);
    end
    SimState.ED_Measure = struct( ...
        'TimeSlot', 0, ...
        'CH_Util', zeros(1, SimParams.N_Node), ...
        'N_ACK', zeros(1, SimParams.N_Node), ...
        'N_Acc', zeros(1, SimParams.N_Node), ...
        'N_Fail', zeros(1, SimParams.N_Node), ...
        'N_Suc', zeros(1, SimParams.N_Node));
    SimState.ED_Stats = struct( ...
        'ProcessedSlots', 0, ...
        'SkippedSlots', 0, ...
        'JumpCount', 0, ...
        'MaxJumpSlots', 0, ...
        'ChannelHistoryBytes', Estimate_Channel_Bytes(SimState.ED_Channel), ...
        'LegacyTxStateBytesAvoided', ...
            double(full_run_slots) * double(SimParams.N_Node));

    use_online_txlog = ...
        isfield(SimParams, 'On_Save_TX_Log') && ...
        SimParams.On_Save_TX_Log && ...
        isfield(SimParams, 'ED_Use_Online_TXLOG_Aggregation') && ...
        SimParams.ED_Use_Online_TXLOG_Aggregation;
    if use_online_txlog
        if isfield(SimState, 'TX_LOG_Access_Log')
            SimState = rmfield(SimState, 'TX_LOG_Access_Log');
        end
        SimState.TX_LOG_Aggregate_Bins = zeros(0, 6);
        SimState.TX_LOG_Pending_Bin_Idx = ...
            zeros(1, SimParams.N_Node);
    end
end

function n_bytes = Estimate_Channel_Bytes(Channel) %#ok<INUSD>
    info = whos('Channel');
    n_bytes = info.bytes;
end

function value = Get_Field_Or_Default(S, field_name, default_value)
    if isfield(S, field_name) && ~isempty(S.(field_name))
        value = S.(field_name);
    else
        value = default_value;
    end
end
